#!/usr/bin/env python3
"""Generate src/data/minimap.ts: the corner map, a line-art orthographic sphere
of Natural Earth coastlines with the three research sites, projected into one
viewBox (ruling15 L0, owner locks L-1 and L-3, 2026-10-20/23).

Source: Natural Earth 110m coastline (public domain). The view centre
(30 W, 25 N) keeps Rio, Amsterdam and Cambridge MA on the visible face with
equal weight. Lines are cut where they cross to the far side, then
Douglas-Peucker simplified so the inline path stays under the check-build
budget (8 KB).
"""
import json
import math
from pathlib import Path

import geopandas as gpd
from shapely.geometry import LineString

SHP = Path.home() / ".cache/naturalearth/ne_110m_coastline.shp"
OUT = Path(__file__).resolve().parent.parent / "src/data/minimap.ts"

LON0, LAT0 = -30.0, 25.0
SIZE, R = 200, 96  # viewBox side and sphere radius, in user units
TOLERANCE_DEG = 0.8
MIN_SPAN = 3.0  # drop islands shorter than this many viewBox units: dust at corner size

PLACES = [
    {"id": "rio", "name": "Rio de Janeiro", "lat": -22.993, "lon": -43.240},
    {"id": "amsterdam", "name": "Amsterdam", "lat": 52.378, "lon": 4.880},
    {"id": "stata", "name": "Cambridge, MA", "lat": 42.362, "lon": -71.091},
]


def ortho(lon, lat):
    """(x, y, visible) in viewBox units for one lon/lat in degrees."""
    l, p = math.radians(lon - LON0), math.radians(lat)
    p0 = math.radians(LAT0)
    cos_c = math.sin(p0) * math.sin(p) + math.cos(p0) * math.cos(p) * math.cos(l)
    x = R * math.cos(p) * math.sin(l)
    y = R * (math.cos(p0) * math.sin(p) - math.sin(p0) * math.cos(p) * math.cos(l))
    return SIZE / 2 + x, SIZE / 2 - y, cos_c > 0


def runs(line):
    """Split one coastline into the stretches on the visible face."""
    cur = []
    for lon, lat in line.coords:
        x, y, vis = ortho(lon, lat)
        if vis:
            cur.append((round(x), round(y)))
        elif cur:
            yield cur
            cur = []
    if cur:
        yield cur


def main():
    gdf = gpd.read_file(SHP)
    parts, verts = [], 0
    for geom in gdf.geometry.simplify(TOLERANCE_DEG, preserve_topology=False):
        if geom is None or geom.is_empty:
            continue
        lines = [geom] if geom.geom_type == "LineString" else list(getattr(geom, "geoms", []))
        for line in lines:
            if not isinstance(line, LineString):
                continue
            for pts in runs(line):
                dedup = [pts[0]] + [p for i, p in enumerate(pts[1:], 1) if p != pts[i - 1]]
                span = sum(math.dist(a, b) for a, b in zip(dedup, dedup[1:]))
                if len(dedup) < 2 or span < MIN_SPAN:
                    continue
                verts += len(dedup)
                fmt = lambda v: f"{v:g}"
                parts.append(f"M{fmt(dedup[0][0])} {fmt(dedup[0][1])}" + "".join(f"L{fmt(x)} {fmt(y)}" for x, y in dedup[1:]))
    path = " ".join(parts)
    places = []
    for p in PLACES:
        x, y, vis = ortho(p["lon"], p["lat"])
        assert vis, f"{p['id']} is on the far side of the sphere"
        places.append({**p, "x": round(x, 1), "y": round(y, 1)})
    OUT.write_text(
        "// Generated by scripts/make-minimap.py — do not hand-edit.\n"
        f"// Natural Earth 110m coastline (public domain), orthographic, centre {abs(LON0):g} W {LAT0:g} N,\n"
        f"// Douglas-Peucker {TOLERANCE_DEG} deg; {verts} vertices.\n"
        f"export const minimapViewBox = '0 0 {SIZE} {SIZE}';\n"
        f"export const minimapSize = {SIZE};\n"
        f"export const minimapRadius = {R};\n"
        f"export const minimapPath = '{path}';\n"
        f"export const minimapPlaces = {json.dumps(places, indent=2, ensure_ascii=False)} as const;\n"
    )
    print(f"wrote {OUT} ({len(path.encode())} B path, {verts} vertices)")


if __name__ == "__main__":
    main()
